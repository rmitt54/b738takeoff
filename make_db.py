#!/usr/bin/env python3
"""Turn airportdb.txt into src/airportdb_data.cpp (a C++ byte array)."""
import sys
src, dst = sys.argv[1], sys.argv[2]
data = open(src, 'rb').read()
with open(dst, 'w') as f:
    f.write('// Generated by tools/make_db.py from OurAirports data. Do not edit.\n')
    f.write('extern const unsigned char kAirportDb[];\nextern const unsigned long kAirportDbSize;\n')
    f.write('const unsigned long kAirportDbSize = %d;\n' % len(data))
    f.write('const unsigned char kAirportDb[] = {\n')
    for i in range(0, len(data), 32):
        f.write(','.join(str(b) for b in data[i:i+32]) + ',\n')
    f.write('0};\n')
